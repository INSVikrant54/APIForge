/**
 * Normalization and validation utility for Gemma 4 test plans
 * Ensures model output complies with the strict test plan schema.
 */

const SUPPORTED_METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'];
const VALID_CATEGORIES = [
  'happy_path',
  'missing_field',
  'type_validation',
  'boundary',
  'business_rule',
  'malformed_input',
  'inconsistent_data'
];
const VALID_SEVERITIES = ['critical', 'high', 'medium', 'low'];

/**
 * Validates and sanitizes a test plan object
 * @param {Object} rawPlan 
 * @param {Object} contextConfig { defaultMethod, defaultPath }
 * @returns {Object} Validated & normalized test suite
 */
export function validateAndNormalizeTestPlan(rawPlan, contextConfig = {}) {
  if (!rawPlan || typeof rawPlan !== 'object') {
    throw new Error('Test plan must be a valid JSON object');
  }

  const suiteName = typeof rawPlan.suiteName === 'string' && rawPlan.suiteName.trim()
    ? rawPlan.suiteName.trim()
    : 'API Behavior Verification Suite';

  const summary = typeof rawPlan.summary === 'string'
    ? rawPlan.summary.trim()
    : 'Automated test suite generated by Gemma 4';

  const assumptions = Array.isArray(rawPlan.assumptions)
    ? rawPlan.assumptions.filter(a => typeof a === 'string' && a.trim() !== '')
    : [];

  const rawTests = Array.isArray(rawPlan.tests) ? rawPlan.tests : [];
  if (rawTests.length === 0) {
    throw new Error('Test plan must contain at least one valid test case');
  }

  // Cap tests at 15 max to avoid unbounded execution overhead
  const cappedTests = rawTests.slice(0, 15);
  const validatedTests = [];

  cappedTests.forEach((t, idx) => {
    if (!t || typeof t !== 'object') return;

    const id = t.id && typeof t.id === 'string' ? t.id : `test-${String(idx + 1).padStart(3, '0')}`;
    const name = t.name && typeof t.name === 'string' ? t.name.trim() : `Test Case #${idx + 1}`;
    const category = VALID_CATEGORIES.includes(t.category) ? t.category : 'boundary';
    const severity = VALID_SEVERITIES.includes(t.severity) ? t.severity : 'medium';
    const description = t.description && typeof t.description === 'string' ? t.description : name;
    const rationale = t.rationale && typeof t.rationale === 'string' ? t.rationale : '';

    // Request validation
    const req = t.request || {};
    const method = typeof req.method === 'string' && SUPPORTED_METHODS.includes(req.method.toUpperCase())
      ? req.method.toUpperCase()
      : (contextConfig.defaultMethod || 'POST');

    const path = typeof req.path === 'string' && req.path.trim() !== ''
      ? req.path.trim()
      : (contextConfig.defaultPath || '/api/demo/orders');

    const headers = typeof req.headers === 'object' && req.headers !== null && !Array.isArray(req.headers)
      ? req.headers
      : { 'Content-Type': 'application/json' };

    const body = req.body !== undefined ? req.body : null;

    // Expected expectations
    const exp = t.expected || {};
    let statusCodes = [];
    if (Array.isArray(exp.statusCodes)) {
      statusCodes = exp.statusCodes.filter(c => typeof c === 'number' && c >= 100 && c <= 599);
    } else if (typeof exp.statusCode === 'number' && exp.statusCode >= 100 && exp.statusCode <= 599) {
      statusCodes = [exp.statusCode];
    } else if (typeof exp.status === 'number' && exp.status >= 100 && exp.status <= 599) {
      statusCodes = [exp.status];
    }

    if (statusCodes.length === 0) {
      // Default fallback: happy path -> 200/201, other -> 400
      statusCodes = category === 'happy_path' ? [200, 201] : [400];
    }

    const expectedDesc = exp.description && typeof exp.description === 'string'
      ? exp.description
      : `Expected HTTP status ${statusCodes.join(' or ')}`;

    // Assertions array
    const rawAssertions = Array.isArray(t.assertions) ? t.assertions : (Array.isArray(exp.assertions) ? exp.assertions : []);
    const assertions = rawAssertions.map((a, aIdx) => ({
      id: a.id || `assert-${id}-${aIdx + 1}`,
      target: a.target || a.path || 'body',
      operator: a.operator || 'equals',
      value: a.value !== undefined ? a.value : null,
      description: a.description || ''
    }));

    // If assertions or expected behavior is uncertain or contract was sparse, flag for review
    const requiresReview = Boolean(
      t.requiresReview ||
      (category === 'inconsistent_data' && statusCodes.length > 1) ||
      (t.assumptions && t.assumptions.length > 0)
    );

    validatedTests.push({
      id,
      name,
      category,
      severity,
      description,
      rationale,
      request: {
        method,
        path,
        headers,
        body
      },
      expected: {
        statusCodes,
        description: expectedDesc,
        assertions
      },
      requiresReview,
      confirmed: !requiresReview // Auto-confirmed if no review needed
    });
  });

  return {
    suiteName,
    summary,
    assumptions,
    tests: validatedTests,
    generatedAt: new Date().toISOString(),
    totalCount: validatedTests.length
  };
}
