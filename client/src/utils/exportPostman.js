/**
 * Bounded Postman Collection v2.1 exporter.
 *
 * The collection is generated from already-redacted test suites; a second
 * redaction pass is applied here so an accidental direct call cannot leak
 * credentials into a downloaded file.
 */

import { redactSecrets } from '../../../server/utils/environmentResolver.js';

export const MAX_EXPORT_ITEMS = 50;
const MAX_BODY_BYTES = 64 * 1024;
const SENSITIVE_HEADERS = new Set(['x-gemini-api-key', 'authorization', 'cookie', 'set-cookie']);

const isRecord = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);

/** Keep templated auth (e.g. "Bearer {{token}}"), drop anything that looks like a real credential. */
function isSafeHeader(name, value) {
  if (!SENSITIVE_HEADERS.has(name.toLowerCase())) return true;
  return /\{\{[^{}]+\}\}/.test(String(value ?? ''));
}

function safeBody(body) {
  if (body === null || body === undefined) return null;
  let text;
  try {
    text = typeof body === 'string' ? body : JSON.stringify(body);
  } catch {
    text = String(body);
  }
  if (new TextEncoder().encode(text).byteLength > MAX_BODY_BYTES) {
    return JSON.stringify({ note: 'Body omitted: exceeds 64 KiB export limit.' });
  }
  return text;
}

function toUrl(path) {
  const raw = typeof path === 'string' && path.trim() ? path.trim() : '/';
  if (/^https?:\/\//i.test(raw)) return { raw };
  return { raw: `{{baseUrl}}${raw.startsWith('/') ? raw : `/${raw}`}` };
}

/** Build a Collection v2.1 object; capped at 50 requests, secrets always redacted. */
export function generatePostmanCollection(testSuite, results = [], secretValues = []) {
  const redacted = Array.isArray(secretValues) && secretValues.length
    ? redactSecrets(testSuite, secretValues)
    : testSuite;
  const tests = Array.isArray(redacted?.tests) ? redacted.tests : [];

  const items = tests.slice(0, MAX_EXPORT_ITEMS).map((test, index) => {
    const requestConfig = isRecord(test.request) ? test.request : {};
    const headers = isRecord(requestConfig.headers) ? requestConfig.headers : {};
    const header = Object.entries(headers)
      .filter(([name, value]) => isSafeHeader(name, value))
      .map(([name, value]) => ({ key: name, value: String(value ?? ''), disabled: false }));

    const bodyText = safeBody(requestConfig.body);
    const url = toUrl(requestConfig.path);
    const method = typeof requestConfig.method === 'string' ? requestConfig.method.toUpperCase() : 'GET';

    return {
      name: typeof test.name === 'string' && test.name.trim() ? test.name : `Request ${index + 1}`,
      request: {
        method,
        header,
        url,
        description: typeof test.description === 'string' ? test.description : '',
        ...(bodyText !== null && ['POST', 'PUT', 'PATCH'].includes(method)
          ? { body: { mode: 'raw', raw: bodyText, options: { raw: { language: 'json' } } } }
          : {})
      },
      response: []
    };
  });

  return {
    info: {
      name: (typeof redacted?.suiteName === 'string' && redacted.suiteName.trim())
        ? redacted.suiteName.trim()
        : 'APIForge Verification Suite',
      description: 'Generated by APIForge. Set the baseUrl collection variable before running.',
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json'
    },
    item: items,
    variable: [{ key: 'baseUrl', value: '', type: 'string' }]
  };
}
